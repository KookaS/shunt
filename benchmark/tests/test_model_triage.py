def test_gate_exits_1_when_a_live_pool_model_is_drop(monkeypatch, capsys) -> None:
    # Drive the gate's real exit path: monkeypatch the verdict computation so the live pool
    # contains a DROP, then assert main() returns 1 (the code sys.exit() forwards) and stderr
    # carries the SH015 ERROR line naming the offending model.
    gate = _load_gate()
    pool = ["base", "front", "dom"]
    rows = [
        triage.TriageRow(
            "base", 1.0, 100, 0.5, 0.4, 0.6, "KEEP", None, None, triage.VERDICT_KEEP, None
        ),
        triage.TriageRow(
            "front", 2.0, 100, 0.9, 0.8, 1.0, "KEEP", None, None, triage.VERDICT_KEEP, None
        ),
        triage.TriageRow(
            "dom", 2.0, 100, 0.2, 0.1, 0.3, "DROP", None, None, triage.VERDICT_DROP, None
        ),
    ]
    monkeypatch.setattr("benchmark.routing.triage.triage_default", lambda: rows)
    monkeypatch.setattr("benchmark.routing._live_pool.packaged_live_pool", lambda: pool)
    # Keep the cold-start constants consistent with the fake pool so only the DROP path
    # is under test — otherwise the F2 constant check adds its own ERROR lines.
    monkeypatch.setattr("shunt.router.cold_start._COLD_START_MODEL", "base")
    monkeypatch.setattr("shunt.router.cold_start._DEFAULT_FALLBACK_MODELS", ["front"])
    monkeypatch.setattr("shunt.router.selection._DEFAULT_COLD_START_MODEL", "base")
    monkeypatch.setattr("shunt.proxy.router._DEFAULT_MODEL", "base")
    assert gate.main() == 1
    err = capsys.readouterr().err
    assert "[SH015 ERROR]" in err
    assert "dom" in err  # the failing model is named on the stderr line


