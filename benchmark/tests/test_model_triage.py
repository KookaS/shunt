# ---------------------------------------------------------------- gate exit convention


def _load_by_path(name: str, path: Path) -> ModuleType:
    spec = importlib.util.spec_from_file_location(name, path)
    assert spec is not None
    assert spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


def _load_gate() -> ModuleType:
    """Import the SH015 gate (a script, not a package) by file path, _shared resolved."""
    lint_dir = _REPO_ROOT / "tools" / "lint"
    _load_by_path("_shared", lint_dir / "_shared.py")
    return _load_by_path("sh015_gate", lint_dir / "check_model_triage.py")


