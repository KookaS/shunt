# The repo root, absolute, so gate-path tests run from a robust cwd.
_REPO_ROOT: Final[Path] = Path(__file__).resolve().parents[2]

# A fixed synthetic pricing + ladder so the pure-function tests are fully explicit.
PRICES: Final[dict[str, float]] = {
    "base": 1.0,
    "cheap": 0.5,
    "dom": 2.0,
    "ovr": 2.0,
    "esc": 5.0,
    "front": 10.0,
    "locked": 3.0,
    "cold": 1.5,
}
LIVE: Final[list[str]] = ["base", "front"]


def cell(passed: bool) -> dict:
    return {"pass": passed}


def nested(n: int, passes: dict[str, int]) -> dict:
    """n co-measured challenges; each model passes the first ``passes[m]`` of them."""
    return {f"t{i}": {m: cell(i < passes[m]) for m in passes} for i in range(n)}


def verdicts(rows: list[triage.TriageRow]) -> dict[str, triage.TriageRow]:
    return {r.model: r for r in rows}


def run_triage(
    live_pool: list[str],
    candidates: list[str],
    matrix: dict,
    ladder: dict[str, Any] | None = None,
    enabled: set[str] | None = None,
    k: int = 20,
    exceptions: dict[str, str] | None = None,
) -> list[triage.TriageRow]:
    enabled = enabled if enabled is not None else set(candidates)
    return triage.triage(live_pool, candidates, matrix, PRICES, ladder, enabled, k, exceptions)


# ----------------------------------------------------------------- positive control (real data)


def test_real_triage_reproduces_committed_pool() -> None:
    path = config.results_csv_path()
    if not path.exists():
        pytest.skip("no real results.csv in this checkout (CI)")
    rows = {r.model: r for r in triage.triage_default()}
    expected = {
        "deepseek-v4-flash": triage.VERDICT_KEEP,
        "zai-glm-5.2": triage.VERDICT_KEEP,
        "kimi-k3": triage.VERDICT_KEEP,
        "qwen3.7-plus": triage.VERDICT_DROP,
        "gpt-5-mini": triage.VERDICT_DROP,
        "kimi-k2.5": triage.VERDICT_DROP,
        "gemini-3.1-pro": triage.VERDICT_UNMEASURED,
        "gpt-5.6-sol": triage.VERDICT_UNMEASURED,
        "claude-fable-5": triage.VERDICT_UNMEASURED,
        "claude-opus-4-8": triage.VERDICT_UNMEASURED,
    }
    for model, expected_verdict in expected.items():
        assert rows[model].verdict == expected_verdict, (
            f"{model}: got {rows[model].verdict}, expected {expected_verdict} "
            f"(n={rows[model].n}, rate={rows[model].marginal_rate:.4f}, "
            f"routine={rows[model].routine_status}, esc={rows[model].esc_verdict})"
        )
    # The gate must pass on the shipped pool: no live-pool model is a DROP.
    assert triage.violations(packaged_live_pool(), list(rows.values())) == []


# ------------------------------------------------------- regenerability / staleness


def test_triage_report_is_regenerable_from_committed_data(tmp_path: Path) -> None:
    # Regenerability: triage_summary.csv is regenerable from committed data — two scratch
    # CLI runs write byte-identical CSV, and the regenerated bytes match the working-tree
    # report when one exists (it is gitignored), so the report cannot drift from committed data.
    path = config.results_csv_path()
    if not path.exists():
        pytest.skip("no real results.csv in this checkout (CI)")
    outs = [tmp_path / "a", tmp_path / "b"]
    for out in outs:
        proc = subprocess.run(
            [sys.executable, "-m", "benchmark.routing.triage", "--out-dir", str(out)],
            cwd=_REPO_ROOT,
            capture_output=True,
            text=True,
        )
        assert proc.returncode == 0, proc.stderr
    a, b = (out / "triage_summary.csv" for out in outs)
    assert a.read_bytes() == b.read_bytes()
    report = triage.default_report_dir() / "triage_summary.csv"
    if report.exists():
        assert a.read_bytes() == report.read_bytes()


# ----------------------------------------------------------------- synthetic routine stratum


def test_disjoint_ci_dominance_is_a_drop() -> None:
    # dom (20/100) is priced above base (50/100) and its Wilson CI top (~0.29) is far below
    # the frontier rate (0.5) at its price — dominated, no escalation evidence.
    matrix = nested(100, {"base": 50, "front": 95, "dom": 20})
    rows = verdicts(run_triage(LIVE, [*LIVE, "dom"], matrix))
    assert rows["dom"].verdict == triage.VERDICT_DROP
    assert rows["dom"].routine_status == triage.VERDICT_DROP


def test_ci_overlapping_the_frontier_is_a_keep() -> None:
    # ovr (45/100) sits below the frontier point rate (0.5) but its CI top overlaps it.
    matrix = nested(100, {"base": 50, "front": 95, "ovr": 45})
    rows = verdicts(run_triage(LIVE, [*LIVE, "ovr"], matrix))
    assert rows["ovr"].verdict == triage.VERDICT_KEEP
    assert rows["ovr"].routine_status == triage.VERDICT_KEEP


def test_cheaper_than_every_live_model_defines_the_envelope() -> None:
    # cheap (0.5) is below every live price; it must KEEP even at a low rate because it is
    # the frontier's low end.
    matrix = nested(100, {"base": 50, "front": 95, "cheap": 10})
    rows = verdicts(run_triage(LIVE, [*LIVE, "cheap"], matrix))
    assert rows["cheap"].verdict == triage.VERDICT_KEEP
    assert rows["cheap"].routine_status == triage.VERDICT_KEEP


def test_small_n_is_insufficient_data_not_drop() -> None:
    # n=5 < K=20: no verdict, never a gate violation.
    matrix = nested(100, {"base": 50, "front": 95})
    matrix.update(
        {f"c{i}": {"base": cell(True), "front": cell(True), "cold": cell(i < 3)} for i in range(5)}
    )
    rows = verdicts(run_triage(LIVE, [*LIVE, "cold"], matrix, k=20))
    assert rows["cold"].verdict == triage.VERDICT_INSUFFICIENT
    assert rows["cold"].exception_note is not None and "K=20" in rows["cold"].exception_note


# ------------------------------------------------------------------ escalation stratum zai shape


def test_marginal_dominated_but_net_helpful_escalation_is_a_keep() -> None:
    # esc (30/100) is routine-DOMINATED (CI top ~0.41 below the 0.5 frontier at its price) but
    # the ladder evidence says the target is NET-HELPFUL vs the cheap base — escalation keeps it.
    matrix = nested(100, {"base": 50, "front": 95, "esc": 30})
    ladder = {
        "base_model": "base",
        "targets": [{"target": "esc", "delta": 0.15, "verdict": "NET-HELPFUL"}],
    }
    rows = verdicts(run_triage(LIVE, [*LIVE, "esc"], matrix, ladder=ladder))
    assert rows["esc"].verdict == triage.VERDICT_KEEP
    assert rows["esc"].routine_status == triage.VERDICT_DROP  # kept on escalation alone
    assert rows["esc"].esc_delta == 0.15
    assert rows["esc"].esc_verdict == "NET-HELPFUL"


def test_net_harmful_escalation_does_not_rescue_a_dominated_model() -> None:
    matrix = nested(100, {"base": 50, "front": 95, "esc": 30})
    ladder = {
        "base_model": "base",
        "targets": [{"target": "esc", "delta": -0.2, "verdict": "NET-HARMFUL"}],
    }
    rows = verdicts(run_triage(LIVE, [*LIVE, "esc"], matrix, ladder=ladder))
    assert rows["esc"].verdict == triage.VERDICT_DROP


# ----------------------------------------------- benchmark-disabled is an unmeasurable exception


def test_benchmark_disabled_model_is_unmeasured_exception() -> None:
    # A registry model that is live but benchmark-disabled has no scored cells; it must be
    # UNMEASURED-EXCEPTION, never DROP, so the gate cannot fail on an unmeasurable slot.
    matrix = nested(100, {"base": 50, "front": 95})
    enabled = {"base", "front"}
    rows = verdicts(run_triage(LIVE, [*LIVE, "locked"], matrix, enabled=enabled))
    assert rows["locked"].verdict == triage.VERDICT_UNMEASURED
    assert rows["locked"].exception_note is not None


# --------------------------------------------------------------------- gate violation helper


def test_violations_flags_a_live_pool_containing_a_drop() -> None:
    matrix = nested(100, {"base": 50, "front": 95, "dom": 20})
    live_with_drop = [*LIVE, "dom"]
    rows = run_triage(live_with_drop, live_with_drop, matrix)
    offending = triage.violations(live_with_drop, rows)
    assert [r.model for r in offending] == ["dom"]


def test_violations_empty_for_a_clean_pool() -> None:
    matrix = nested(100, {"base": 50, "front": 95, "ovr": 45})
    rows = run_triage(LIVE, [*LIVE, "ovr"], matrix)
    assert triage.violations(LIVE, rows) == []


def test_benchmark_disabled_and_low_n_live_models_never_violate() -> None:
    # The two exempt verdicts — UNMEASURED-EXCEPTION and INSUFFICIENT-DATA — must never
    # surface as gate violations, even inside the live pool.
    matrix = nested(100, {"base": 50, "front": 95})
    matrix.update(
        {f"c{i}": {"base": cell(True), "front": cell(True), "cold": cell(i < 3)} for i in range(5)}
    )
    live_pool = [*LIVE, "locked", "cold"]
    enabled = {"base", "front", "cold"}
    rows = run_triage(live_pool, live_pool, matrix, enabled=enabled, k=20)
    assert triage.violations(live_pool, rows) == []


# -------------------------------------------------------------- named exceptions (SH015)


def test_named_exception_rescues_a_measured_drop_from_violations() -> None:
    # Without an exception this pool violates (see the existing
    # test_violations_flags_a_live_pool_containing_a_drop); with one, the row is
    # EXCEPTION, advisory via exceptioned(), never a gate offence.
    matrix = nested(100, {"base": 50, "front": 95, "dom": 20})
    live_with_drop = [*LIVE, "dom"]
    reason = "retained for the region-specific eval track"
    rows = run_triage(live_with_drop, live_with_drop, matrix, exceptions={"dom": reason})
    by_model = verdicts(rows)
    assert by_model["dom"].verdict == triage.VERDICT_EXCEPTION
    assert by_model["dom"].exception_note == reason
    assert triage.violations(live_with_drop, rows) == []
    assert [r.model for r in triage.exceptioned(live_with_drop, rows)] == ["dom"]


def test_named_exception_does_not_mask_unmeasured_or_insufficient() -> None:
    # The exception is for measured-DROP models only: an unmeasured or under-measured model
    # named in exceptions keeps its exempt verdict, never upgraded or downgraded.
    matrix = nested(100, {"base": 50, "front": 95})
    enabled = {"base", "front"}
    rows = verdicts(
        run_triage(
            LIVE,
            [*LIVE, "locked"],
            matrix,
            enabled=enabled,
            exceptions={"locked": "reason"},
        )
    )
    assert rows["locked"].verdict == triage.VERDICT_UNMEASURED
    matrix.update(
        {f"c{i}": {"base": cell(True), "front": cell(True), "cold": cell(i < 3)} for i in range(5)}
    )
    rows_cold = verdicts(
        run_triage(LIVE, [*LIVE, "cold"], matrix, k=20, exceptions={"cold": "reason"})
    )
    assert rows_cold["cold"].verdict == triage.VERDICT_INSUFFICIENT


def test_named_exception_does_not_apply_to_a_keep() -> None:
    matrix = nested(100, {"base": 50, "front": 95, "ovr": 45})
    rows = verdicts(run_triage(LIVE, [*LIVE, "ovr"], matrix, exceptions={"ovr": "reason"}))
    assert rows["ovr"].verdict == triage.VERDICT_KEEP
    assert rows["ovr"].exception_note is None


