# -------------------------------------------------------------------- config-error guard


def test_unpriced_candidate_raises_instead_of_silent_keep() -> None:
    # A candidate with no registry price is a config error in the pure function: it must
    # raise rather than silently KEEP via a NaN price.
    matrix = nested(100, {"base": 50, "front": 95, "phantom": 20})
    with pytest.raises(ValueError, match="without a registry price"):
        run_triage(LIVE, [*LIVE, "phantom"], matrix)
